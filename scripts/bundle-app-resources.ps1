param()

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot
$Resources = Join-Path $Root "apps\desktop\resources"
$ScriptsTarget = Join-Path $Resources "scripts"
$ScriptsTarget = [IO.Path]::GetFullPath($ScriptsTarget)
if (-not $ScriptsTarget.StartsWith([IO.Path]::GetFullPath($Root) + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw "Backend resource target is outside the workspace: $ScriptsTarget"
}

if (Test-Path $ScriptsTarget) {
    Remove-Item $ScriptsTarget -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $ScriptsTarget | Out-Null

$ScriptFiles = @(
    "api_server.py",
    "media_http.py",
    "model_catalog.py",
    "model_catalog.json",
    "model_manager.py",
    "model_capabilities.py",
    "device_adapters.py",
    "flux2_klein_pipeline.py",
    "qwen3_tts_worker.py",
    "qwen21_turbo_openvino.py",
    "qwen21_turbo_download.py",
    "qwen21_turbo_model_catalog.json",
    "tts_generation_worker.py",
    "tts_model_download.py",
    "tts_model_catalog.json",
    "requirements-qwen3-tts-runtime.txt",
    "requirements-qwen21-turbo-export.txt",
    "requirements-qwen21-turbo-overlay.txt",
    "install-qwen3-tts.ps1",
    "gallery_store.py",
    "generation_worker.py",
    "storage_manager.py",
    "bootstrap_install.py"
)

foreach ($file in $ScriptFiles) {
    $source = Join-Path $Root "scripts\$file"
    if (-not (Test-Path $source)) {
        throw "Missing script: $source"
    }
    Copy-Item $source (Join-Path $ScriptsTarget $file) -Force
}

Write-Host "Bundled backend scripts -> $ScriptsTarget"

$LicensesTarget = [IO.Path]::GetFullPath((Join-Path $Resources 'licenses'))
if (-not $LicensesTarget.StartsWith([IO.Path]::GetFullPath($Root) + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'License resource target is outside the workspace.'
}
if (Test-Path -LiteralPath $LicensesTarget) { Remove-Item -LiteralPath $LicensesTarget -Recurse -Force }
New-Item -ItemType Directory -Force -Path $LicensesTarget | Out-Null
Copy-Item -LiteralPath (Join-Path $Root 'LICENSE') -Destination (Join-Path $LicensesTarget 'fern.txt')
foreach ($package in @('react', 'react-dom', 'scheduler', 'lucide-react')) {
    Copy-Item -LiteralPath (Join-Path $Root "node_modules/$package/LICENSE") -Destination (Join-Path $LicensesTarget "$package.txt")
}


$TtsSource = Join-Path $Root "scripts/tts_runtime"
$TtsTarget = Join-Path $ScriptsTarget "tts_runtime"
# Keep the vendored inference source and its small tokenizer data/licensing files;
# never copy generated bytecode, recordings, model weights, or local configuration.
Get-ChildItem -LiteralPath $TtsSource -Recurse -File | Where-Object {
    $_.Extension -in @('.py', '.npz') -or $_.Name -in @('LICENSE-QWEN', 'LICENSE-OPENVINO-NOTEBOOKS', 'NOTICE')
} | ForEach-Object {
    $relative = $_.FullName.Substring($TtsSource.Length).TrimStart([IO.Path]::DirectorySeparatorChar)
    $destination = Join-Path $TtsTarget $relative
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
    Copy-Item -LiteralPath $_.FullName -Destination $destination -Force
}
