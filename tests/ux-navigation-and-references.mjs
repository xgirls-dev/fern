import assert from "node:assert/strict";
import { expect } from "@playwright/test";
import { fixture } from "./ui-fixture.mjs";

const { page, state, errors, dir, close } = await fixture({ threadCount: 100 });
const button = (name) => page.getByRole("button", { name, exact: true });
const newThread = async (kind) => { await page.locator(".sidebar-new-menu > button").click(); await page.getByRole("menuitem", { name: `New ${kind} thread` }).click(); };
const longName = "A custom image model with a very long repository name that should always stay on one line";
try {
  state.installedModels = [{ id: "9b", label: "Klein 9B" }, { id: "4b", label: "Klein 4B" }, { id: "custom-long", label: longName, family: "sdxl" }, { id: "tame-pony-v25-sdxl", label: "Tame Pony · SDXL" }];
  await page.route("**/api/models", (route) => route.fulfill({ json: { models: state.installedModels.map((model) => ({ ...model, installed: true, bytes: 4e9, downloaded: 4e9, state: "installed" })), customImageDownload: { status: "idle" } } }));
  await page.reload();
  await page.locator("#prompt").waitFor();
  await expect(page.locator(".sidebar-new-button")).toHaveCount(1);
  await page.locator(".sidebar-new-menu > button").click();
  await expect(page.getByRole("menuitem", { name: /New .* thread/ })).toHaveCount(3);
  await page.keyboard.press("Escape");
  const scrolling = await page.locator(".sidebar-scroll-area").evaluate((sidebar) => ({ owner: getComputedStyle(sidebar).overflowY, overflowing: sidebar.scrollHeight > sidebar.clientHeight, nested: [...sidebar.querySelectorAll(".sidebar-threads")].map((section) => getComputedStyle(section).overflowY) }));
  assert.equal(scrolling.owner, "auto"); assert(scrolling.overflowing);
  assert(scrolling.nested.every((value) => value === "visible"), "Thread groups must share the sidebar scroll container");
  await page.locator(".sidebar-scroll-area").evaluate((element) => { element.scrollTop = element.scrollHeight; });
  await expect(button("Models")).toBeInViewport();
  await expect(button("Preferences")).toBeInViewport();
  await page.locator(".sidebar-scroll-area").evaluate((element) => { element.scrollTop = 0; });

  await button("Models").click();
  await page.getByRole("heading", { name: "Models", exact: true }).waitFor();
  await page.getByRole("heading", { name: "Image models", exact: true }).waitFor();
  const modelLayout = await page.locator(".models-view").evaluate((view) => ({ width: view.getBoundingClientRect().width, mainWidth: view.closest("main").getBoundingClientRect().width, bodyOverflow: view.querySelector(".models-body").scrollWidth > view.querySelector(".models-body").clientWidth }));
  assert(Math.abs(modelLayout.width - modelLayout.mainWidth) <= 2, "Models must fill the main view, not an inspector column");
  assert.equal(modelLayout.bodyOverflow, false, "Model management must not scroll horizontally");
  await page.screenshot({ path: `${dir}/models-image-panel.png` });
  await expect(page.getByLabel("Hugging Face repository")).toBeHidden();
  await page.getByText("Add custom model", { exact: true }).click();
  await expect(page.getByLabel("Custom image model family")).toBeVisible();
  await button("Text").click();
  await page.getByRole("heading", { name: "Text models", exact: true }).waitFor();
  await expect(button("Add local model")).toBeVisible();
  await page.screenshot({ path: `${dir}/models-text-panel.png` });
  await button("Audio").click();
  await page.getByRole("heading", { name: "Audio models", exact: true }).waitFor();
  await expect(page.getByRole("heading", { name: "Custom Voice · 0.6B" })).toBeVisible();
  await button("Preferences").click();
  await expect(page.getByRole("heading", { name: "Image models" })).toHaveCount(0);

  await page.locator('.sidebar-thread-button[data-thread-id="study"]').click();
  await page.getByRole("button", { name: "Image model: Klein 9B" }).click();
  const modelRows = page.getByRole("menuitemradio");
  const rows = await modelRows.evaluateAll((items) => items.map((item) => ({ height: item.getBoundingClientRect().height, whitespace: getComputedStyle(item.querySelector(".composer-model-label")).whiteSpace, width: item.getBoundingClientRect().width, overflow: item.scrollWidth > item.clientWidth })));
  assert(rows.every((row) => row.height === 34 && row.whitespace === "nowrap" && !row.overflow), JSON.stringify(rows));
  await page.screenshot({ path: `${dir}/navigation-model-menu.png` });
  await page.getByRole("menuitemradio", { name: "Klein 4B", exact: true }).click();
  const png = async (color) => Buffer.from(await page.evaluate((fill) => { const canvas = document.createElement("canvas"); canvas.width = canvas.height = 8; const context = canvas.getContext("2d"); context.fillStyle = fill; context.fillRect(0, 0, 8, 8); return canvas.toDataURL("image/png").split(",")[1]; }, color), "base64");
  const red = await png("red"), blue = await png("blue");
  await page.getByLabel("Reference image file").setInputFiles([{ name: "red.png", mimeType: "image/png", buffer: red }, { name: "blue.png", mimeType: "image/png", buffer: blue }]);
  await expect(page.locator(".composer-reference")).toHaveCount(2);
  await button("Move reference 2 earlier").click();
  await expect(page.locator(".composer-reference small").first()).toHaveText("blue.png");
  await page.getByLabel("Reference image file").setInputFiles([{ name: "third.png", mimeType: "image/png", buffer: red }, { name: "fourth.png", mimeType: "image/png", buffer: blue }]);
  await expect(page.locator(".composer-reference")).toHaveCount(4);
  await expect(button("Add reference image")).toBeDisabled();
  await button("Remove reference 4").click();
  await expect(page.locator(".composer-reference")).toHaveCount(3);
  await page.locator("#prompt").fill("Combine Image 1 and Image 2 in the style of Image 3");
  await button("Generate image").click();
  await expect.poll(() => state.payloads.length).toBe(1);
  assert.equal(state.payloads[0].reference_images.length, 3);
  assert.equal(state.payloads[0].reference_images[0].split(",")[1], blue.toString("base64"));
  await page.reload();
  await expect(page.locator(".composer-reference")).toHaveCount(3);
  await expect(page.locator(".composer-reference small").first()).toHaveText("blue.png");
  await newThread("image");
  await expect(page.locator(".composer-reference")).toHaveCount(0);
  await page.locator('.sidebar-thread-button[data-thread-id="study"]').click();
  await expect(page.locator(".composer-reference")).toHaveCount(3);
  await page.getByRole("button", { name: "Image model: Klein 4B" }).click();
  await page.getByRole("menuitemradio", { name: "Tame Pony · SDXL", exact: true }).click();
  await expect(page.locator(".composer-reference")).toHaveCount(3);
  await expect(button("Generate image")).toBeDisabled();
  await expect(page.getByText("This model generates from text only. Remove the references or select Klein to edit them.")).toBeVisible();
  await page.getByRole("button", { name: "Image model: Tame Pony · SDXL" }).click();
  await page.getByRole("menuitemradio", { name: "Klein 4B", exact: true }).click();
  for (const width of [1440, 1080, 720]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Horizontal overflow at ${width}px`);
    await page.screenshot({ path: `${dir}/references-${width}.png` });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await button("Toggle theme").click();
  await page.screenshot({ path: `${dir}/references-dark.png` });
  await newThread("text");
  await page.getByRole("button", { name: "Text model", exact: true }).click();
  await page.getByRole("menuitem", { name: "Manage models" }).click();
  await page.getByRole("heading", { name: "Text models", exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log("Navigation, Models view, single sidebar scroll, one-line model items, multi-reference order/removal/persistence, and incompatible-model handling passed.");
} finally { await close(); }
